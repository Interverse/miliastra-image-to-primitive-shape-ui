/* Regenerate the browser's standalone player after canonical Lua/kernel edits. */
'use strict';
const fs=require('fs'),path=require('path'),kernels=require('./animation-kernel.cjs');
function source(){
 const read=name=>fs.readFileSync(path.join(__dirname,'lua',name),'utf8');
 let shared=read('animation-shared.lua');
 shared=shared.replace('local function signed','-- @BEGIN_RANGE_CODEC@\n'+read('animation-range.lua')+'\n-- @END_RANGE_CODEC@\nlocal function signed')
  .replace('DATA=nil books=nil','releaseRange() DATA=nil books=nil')
  .replace('colors={} keys={}','releaseRange() colors={} keys={}')
  .replace('local p=components[a+4]*16777216+components[a+3]*65536+components[a+2]*256+components[a+1]',
   'local g=components[a+2] local r,b=components[a+3],components[a+1] if COLOR_TRANSFORM then r=(r+g)%256 b=(b+g)%256 end local p=components[a+4]*16777216+r*65536+g*256+b')
  .replace('local r,g,b=components[a+3],components[a+2],components[a+1] if COMPACT','if COMPACT');
 let fast=read('animation-fast.lua')
  .replace('-- @FAST_DISPATCH@',kernels.generate({layout:'hybrid',blockSize:8,unroll:1,hoist:false}))
  .replace('-- @APPEND_COMMAND@',kernels.append('hybrid',8))
  .replace('-- @NATIVE_TRANSACTION@','local function initNativePolicy() return false end\nlocal function nativeTransaction(apply,target) apply(target) end\nlocal function destroyNativePolicy() end')
  .replace(/^local (?:NATIVE_TRANSACTION_MODE|AUTO_NATIVE_UPDATES|NATIVE_TEST_SECONDS)=[^\r\n]*\r?\n/gm,'');
 return '/* Generated by scripts/build-animation-player.cjs; edit scripts/lua and animation-kernel.cjs. */\n"use strict";\nconst AnimationPlayerRuntime='+JSON.stringify(shared+'\n'+fast)+';\nif(typeof module!=="undefined")module.exports=AnimationPlayerRuntime;\n';
}
if(require.main===module)fs.writeFileSync(path.join(__dirname,'../js/animation-player-runtime.js'),source());
module.exports={source};
